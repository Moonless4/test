export const HOTEL_BY_ID = HOTELS.reduce(
  (acc, h) => {
    acc[h.id] = h;
    return acc;
  },
  {} as Record<string, Hotel>,
);

export function hotelById(id: string): Hotel | null {
  return HOTEL_BY_ID[id] ?? null;
}

/** حداقل قیمت شب اقامت در یک شهر */
export function minPriceInCity(cityName: string): number | null {
  const list = HOTELS.filter((h) => h.cityName === cityName || h.cityCode === cityName);
  if (!list.length) return null;
  return Math.min(...list.map((h) => h.pricePerNight));
}
